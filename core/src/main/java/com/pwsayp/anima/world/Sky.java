package com.pwsayp.anima.world;

import net.minecraft.core.BlockPos;
import net.minecraft.world.level.LevelReader;

/**
 * Открыто ли над блоком небо.
 *
 * <p>Мелочь на одну строку, и всё же ей место в ядре: строка эта неочевидная и один раз уже
 * стоила мода. Небо проверяется <b>над</b> блоком, а не в нём самом. Посев небо не
 * перекрывает, поэтому для грядки разницы нет, а вот листва перекрывает: у верхнего блока
 * кроны небо «занято» им же, и по проверке в самом блоке крона не годилась никогда —
 * деревья стояли целыми, сколько бы саранчи над ними ни висело.</p>
 *
 * <p>С проверкой над блоком всё встаёт на место само: верхний слой кроны открыт небу,
 * нижние закрыты своей же листвой, а грядки под стеклянной крышей в безопасности.</p>
 */
public final class Sky {
    private Sky() {}

    /** Видно ли небо прямо над этим блоком. */
    public static boolean openAbove(final LevelReader level, final BlockPos pos) {
        return level.canSeeSky(pos.above());
    }
}
